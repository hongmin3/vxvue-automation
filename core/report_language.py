def describe_step(tc_id, title):
    """TC/제목에 맞는 사용자용 수행 문장을 반환한다.

    매칭되지 않은 새 Step은 정직한 일반 문장으로 표시하되 두 번째 반환값을
    False로 두어 리포트 품질 검사와 개발 문서에서 사전 등록 필요를 알린다.
    """
    text = str(title).strip()
    # 단독 실행 명령의 실제 ID와 초기 설계에서 사용한 이름을 한 사전으로 관리한다.
    tc_id = {
        "TC_Setting_ExportImport": "Setting_Export_Import",
    }.get(tc_id, tc_id)
    for fragment, description in STEP_ACTIVITY_RULES.get(tc_id, ()):
        if fragment in text:
            return description, True
    for fragment, description in COMMON_STEP_RULES:
        if fragment in text:
            return description, True
    return ("'%s' 항목을 실행하고, 화면·데이터베이스·생성 파일·로그 중 이 단계에서 "
            "확보 가능한 근거를 기대 결과와 비교한다." % text), False
